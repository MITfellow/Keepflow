-- Keepflow waitlist schema
-- Run this in the Supabase SQL editor, or with `supabase db push`.
-- The application talks to this table only through the service role key.

create extension if not exists citext;

create table if not exists public.waitlist (
  id uuid primary key default gen_random_uuid(),
  email citext not null unique,
  created_at timestamptz not null default now(),
  referral_code text not null unique,
  referred_by uuid references public.waitlist (id) on delete set null,
  referral_count integer not null default 0 check (referral_count >= 0),
  position bigint generated always as identity unique,
  source text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  ip_hash text,
  unsubscribe_token uuid not null default gen_random_uuid() unique,
  unsubscribed_at timestamptz
);

create index if not exists waitlist_created_at_idx
  on public.waitlist (created_at desc);

create index if not exists waitlist_referred_by_idx
  on public.waitlist (referred_by)
  where referred_by is not null;

create index if not exists waitlist_active_idx
  on public.waitlist (created_at desc)
  where unsubscribed_at is null;

-- Keep the referrer's count in sync for every successful referral.
-- The application also reads the count after insert, so this trigger is the
-- single source of truth for credits.
create or replace function public.increment_referral_count()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.referred_by is not null and new.referred_by <> new.id then
    update public.waitlist
      set referral_count = referral_count + 1
      where id = new.referred_by
        and unsubscribed_at is null;
  end if;

  return new;
end;
$$;

drop trigger if exists waitlist_increment_referral_count on public.waitlist;

create trigger waitlist_increment_referral_count
after insert on public.waitlist
for each row execute function public.increment_referral_count();

-- Row-level security: enabled with no policies. Only the service role
-- (used by server routes) can read or write. Anon and authenticated clients
-- have no access, even if they discover the table name.
alter table public.waitlist enable row level security;
alter table public.waitlist force row level security;

revoke all on table public.waitlist from anon, authenticated;
grant select, insert, update, delete on table public.waitlist to service_role;

comment on table public.waitlist is
  'Pre-launch waitlist. RLS is enabled with no public policies; server routes use the service role.';
comment on column public.waitlist.email is
  'Lowercased email address. Unique by citext.';
comment on column public.waitlist.referral_code is
  'Private code used in referral links. Generated by the application.';
comment on column public.waitlist.position is
  'Insertion order. Effective position applies referral lift in the app.';
comment on column public.waitlist.ip_hash is
  'Salted one-way hash of the request IP. Never the raw address.';
comment on column public.waitlist.unsubscribe_token is
  'Private token used by the unsubscribe page and List-Unsubscribe header.';
